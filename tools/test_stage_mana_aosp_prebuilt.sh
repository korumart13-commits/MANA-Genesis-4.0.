#!/usr/bin/env bash
set -euo pipefail
SCRIPT="tools/stage_mana_aosp_prebuilt.sh"
bash -n "$SCRIPT"
grep -F 'android_app_import {' "$SCRIPT"
grep -F 'presigned: false' "$SCRIPT"
grep -F 'certificate: "platform"' "$SCRIPT"
grep -F 'APKSIGNER="${APKSIGNER:-apksigner}"' "$SCRIPT"
grep -F 'refusing to re-sign an already signed APK' "$SCRIPT"
grep -F 'privileged: false' "$SCRIPT"
! grep -F 'privileged: true' "$SCRIPT"
grep -F 'com.mana.launcher' "$SCRIPT"
grep -F 'ManaEngineBridgeService' "$SCRIPT"
grep -F 'com.mana.permission.BIND_BRAIN' "$SCRIPT"
grep -F 'mana-source-backup' "$SCRIPT"
VERIFY_SCRIPT="tools/verify_mana_platform_signature.sh"
bash -n "$VERIFY_SCRIPT"
grep -F 'verify --verbose --print-certs' "$VERIFY_SCRIPT"
grep -F 'platform.x509.pem' "$VERIFY_SCRIPT"
grep -F 'MANA APK signer does not match' "$VERIFY_SCRIPT"
echo "MANA AOSP staging and platform-signature verifier static checks passed."
